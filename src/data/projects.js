export const CATEGORIES = ["Full-Stack", "Frontend", "Java", "Data Analytics", "Learning"];

export const getProject = (slug) => PROJECTS.find((p) => p.slug === slug);

export function projectStats(p) {
  const rs = p.repos.map((r) => ({ ...r, ...repoStats(r.name), url: gh(r.name) }));
  const loc = p.repos.reduce((sum, r) => sum + Object.values(activity.locByRepo[r.name] ?? {}).reduce((a, b) => a + b, 0), 0);
  const dates = rs.flatMap((r) => [r.first, r.last]).filter(Boolean).sort();
  return {
    repos: rs,
    commits: rs.reduce((a, r) => a + r.commits, 0),
    loc,
    first: dates[0] ?? null,
    last: dates[dates.length - 1] ?? null,
  };
}
